/**
 * ============================================================================
 *  data/musicList.ts —— 背景音乐播放列表
 * ----------------------------------------------------------------------------
 *  默认列表为空，避免引用外部链接导致的 CORS / 404 控制台报错。
 *  添加音乐两种方式（二选一）：
 *   1) 直接把 mp3 放到 public/music/ 目录，然后点播放器上的「导入」按钮选择本地文件；
 *   2) 在这里手动填写：src 写成相对路径如 /music/xxx.mp3（文件需存在于 public/music/）。
 *  封面 cover 可用本地 public/ 下的图片或任意图片 URL。
 * ============================================================================
 */

export interface Track {
  id: string
  title: string
  artist: string
  /** 封面占位图 */
  cover: string
  /** 音频地址（支持相对路径或完整 URL） */
  src: string
}

export const musicList: Track[] = []
